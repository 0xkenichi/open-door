// Packs the static web app (web/) into src/web4-files.ts so the contract can serve it via web4.
// Runs automatically before `npm run build`.
import fs from "node:fs";
import path from "node:path";

const TYPES = { ".html": "text/html; charset=utf-8", ".js": "application/javascript; charset=utf-8", ".css": "text/css; charset=utf-8" };
const files = {};
for (const name of fs.readdirSync("web")) {
  const type = TYPES[path.extname(name)];
  if (!type) continue;
  files[`/${name}`] = { t: type, b: fs.readFileSync(path.join("web", name)).toString("base64") };
}
const out = `// Generated by scripts/gen-web4.mjs from web/. Do not edit by hand.\nexport const WEB4_FILES: Record<string, { t: string; b: string }> = ${JSON.stringify(files, null, 1)};\n`;
fs.writeFileSync("src/web4-files.ts", out);
console.log(`web4: packed ${Object.keys(files).length} files (${Math.round(out.length / 1024)} KB)`);
